#!/usr/bin/env node
// Builds lib/jobs/titleVocabulary.data.js — the words job titles and employer names actually use, with how many
// listings use each, so the job search can fix a misspelt query word ("cashir" → "cashier", "electrition" →
// "electrician") without a model or a network call. Read-only: pages public.jobs (title, company) by id.
// Usage: SUPABASE_URL=… SUPABASE_SERVICE_KEY=… node scripts/jobs/build-title-vocabulary.mjs [minListings=3]
//    or: node scripts/jobs/build-title-vocabulary.mjs --from <dump.jsonl> [minListings=3]   (lines of [title, company])
import fs from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
const fromIdx = args.indexOf('--from');
const dumpPath = fromIdx >= 0 ? args[fromIdx + 1] : null;
const MIN = Number(args.filter((a, i) => a !== '--from' && i !== fromIdx + 1)[0] || 3);

const words = (s) => [...new Set(String(s || '').toLowerCase().replace(/[^a-z0-9+#]+/g, ' ').split(' ').filter((w) => w.length >= 3 && /[a-z]/.test(w) && !/\d/.test(w)))];
const count = new Map();
const add = (title, company) => { for (const w of new Set([...words(title), ...words(company)])) count.set(w, (count.get(w) || 0) + 1); };

let n = 0;
if (dumpPath) {
  for (const line of fs.readFileSync(dumpPath, 'utf8').split('\n')) { if (!line) continue; const [t, c] = JSON.parse(line); add(t, c); n++; }
} else {
  const U = process.env.SUPABASE_URL, K = process.env.SUPABASE_SERVICE_KEY;
  if (!U || !K) { console.error('SUPABASE_URL and SUPABASE_SERVICE_KEY are required (or pass --from <dump.jsonl>)'); process.exit(1); }
  let last = '00000000-0000-0000-0000-000000000000';
  for (;;) {
    const r = await fetch(`${U}/rest/v1/jobs?select=id,title,company&id=gt.${last}&order=id.asc&limit=1000`, { headers: { apikey: K, Authorization: `Bearer ${K}` } });
    if (!r.ok) throw new Error(`jobs read ${r.status}`);
    const rows = await r.json();
    if (!rows.length) break;
    for (const x of rows) { add(x.title, x.company); n++; }
    last = rows[rows.length - 1].id;
  }
}

const kept = [...count].filter(([, c]) => c >= MIN).sort((a, b) => b[1] - a[1]);
const body = kept.map(([w, c]) => `${w} ${c}`).join('\n');
const out = `// GENERATED by scripts/jobs/build-title-vocabulary.mjs from ${n} listings' titles and employer names (${new Date().toISOString().slice(0, 10)}).
// ${kept.length} words used by at least ${MIN} listings, most used first. Do not edit by hand — re-run the script.
// Format: one word per line, "word listings".
export const TITLE_VOCABULARY = ${JSON.stringify(body)};
`;
const dest = path.join(path.dirname(new URL(import.meta.url).pathname), '..', '..', 'lib', 'jobs', 'titleVocabulary.data.js');
fs.writeFileSync(dest, out);
console.log(`wrote ${dest}: ${kept.length} words from ${n} listings, ${(out.length / 1024).toFixed(0)} KB`);
