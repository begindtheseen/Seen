import { launch, shot, go, text } from './_r1_tasha_lib.mjs'
const PW = process.env.TP; const EMAIL = 'tasha.signup.r1@seenjobs.io'
const { ctx, page, logs } = await launch()
await go(page, '/', 2500)
const t0 = Date.now()
await page.getByRole('link', { name: 'Get started' }).first().click()
await page.waitForTimeout(2500)
console.log('after Get started →', page.url(), (Date.now()-t0)+'ms')
await shot(page, '03-signup-form-empty')
console.log((await text(page, 'main')).slice(0, 1500))
await page.fill('#su-email', EMAIL)
await page.fill('#su-pw', PW)
await shot(page, '03-signup-form-filled')
// password strength / show toggle?
const t1 = Date.now()
await page.getByTestId('signup-submit').click()
await page.waitForTimeout(4000)
console.log('after submit →', page.url(), (Date.now()-t1)+'ms')
await shot(page, '03-signup-after-submit')
console.log((await text(page, 'main')).slice(0, 2000))
console.log(logs.filter(l=>!/preload|vercel.live/.test(l)).join('\n'))
await ctx.close()
